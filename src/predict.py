"""Predict from a CSV using named columns and basic input validation."""
import argparse
import json
import warnings
import joblib
import numpy as np
import pandas as pd
from common import ROOT, FEATURES

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', type=str, default=str(ROOT / 'examples/inputs.csv'))
    parser.add_argument('--output', type=str, default=str(ROOT / 'results/example_predictions.csv'))
    args = parser.parse_args()
    frame = pd.read_csv(args.input)
    missing = set(FEATURES) - set(frame.columns)
    if missing:
        raise ValueError(f'Missing columns: {sorted(missing)}')
    X = frame[FEATURES].apply(pd.to_numeric, errors='raise')
    if not len(X) or not np.isfinite(X.to_numpy()).all() or (X < 0).any().any() or (X.age <= 0).any():
        raise ValueError('Provide finite, nonnegative inputs and strictly positive age.')
    meta = json.loads((ROOT / 'models/metadata.json').read_text(encoding='utf-8'))
    for name in FEATURES:
        if ((X[name] < meta['training_min'][name]) | (X[name] > meta['training_max'][name])).any():
            warnings.warn(f'{name} is outside the training range; extrapolation is unreliable.')
    # Only load the model supplied by this project or generated by train.py.
    model = joblib.load(ROOT / 'models/model.joblib')
    frame['predicted_strength_mpa'] = model.predict(X)
    frame.to_csv(args.output, index=False)
    print(frame.to_string(index=False))

if __name__ == '__main__':
    main()
